import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { dec2, fr, gcd, r2, r3 } from '../lib/dec'

const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}
const PC = '\u066A'

// نسبة مئوية إلى كسر
const pToFQ = (): Question => {
  const p = pick([12, 15, 16, 24, 25, 35, 36, 40, 45, 60, 64, 75, 80, 85])
  const g = gcd(p, 100), n = p / g, d = 100 / g
  return {
    kind: 'choice',
    prompt: `اكتبي $${p}${PC}$ على صورة كسر اعتيادي في أبسط صورة.`,
    options: [
      { text: `$${fr(n, d)}$`, correct: true, why: `برافو! 🎉 $${p}${PC} = ${fr(p, 100)}$ ثم قسمنا على $${g}$ فصار $${fr(n, d)}$ ✔️` },
      { text: `$${fr(p, 100)}$`, why: 'صحيحة، بس مو **بأبسط صورة**! 💡 اقسمي البسط والمقام على قاسمهم المشترك الأكبر.' },
      { text: `$${fr(d, n)}$`, why: 'قلبتي الكسر! 🔄 النسبة المئوية جزء من ١٠٠.' },
      { text: `$${fr(n, 100)}$`, why: 'قسمتي البسط بس! 😅 لازم نقسم البسط **والمقام** على نفس العدد.' },
    ],
  }
}

// نسبة أكبر من ١٠٠٪
const overQ = (): Question => {
  const p = pick([120, 125, 150, 175, 190, 225])
  const g = gcd(p, 100), n = p / g, d = 100 / g
  const w = Math.floor(n / d), r = n % d
  return {
    kind: 'choice',
    prompt: `بيعت بناية بـ$${p}${PC}$ من سعرها الأصلي. اكتبي النسبة على صورة عدد كسري في أبسط صورة.`,
    options: [
      { text: `$${w}${fr(r, d)}$`, correct: true, why: `برافو! 🎉 $${p}${PC} = ${fr(p, 100)}$، وبما إنها أكبر من ١٠٠٪ فهي عدد أكبر من ١ ✔️` },
      { text: `$${fr(r, d)}$`, why: 'نسيتي العدد الصحيح! 😅 النسبة أكبر من ١٠٠٪ يعني أكبر من ١ كامل.' },
      { text: `$${w}${fr(r, 100)}$`, why: 'الكسر الجزئي مو **بأبسط صورة**! 💡 اقسمي البسط والمقام على قاسمهم المشترك.' },
      { text: `$${fr(d, n)}$`, why: 'قلبتي الكسر! 🔄 هاد أقل من ١.' },
    ],
  }
}

// كسر إلى نسبة (مقام عامل من ١٠٠)
const fToPQ = (): Question => {
  const den = pick([2, 4, 5, 10, 20, 25, 50]), num = rand(1, den - 1), ans = (num * 100) / den
  return {
    kind: 'numeric',
    prompt: `اكتبي $${fr(num, den)}$ على صورة نسبة مئوية (اكتبي العدد بدون الرمز).`,
    answer: ans,
    wrong: wr(ans, [
      { value: r3(num / den), why: 'هاد الكسر العشري! 🔍 لازم نضربه بـ١٠٠.' },
      { value: 100 / den, why: 'نسيتي تضربي بالبسط! 😅 هاد قيمة جزء واحد بس.' },
      { value: num * den, why: 'ضربتي البسط بالمقام! 🔄 نريد مقاماً ١٠٠.' },
    ]),
    why: `نضرب البسط والمقام بعدد يخلي المقام ١٠٠: $${den} × ${100 / den} = 100$.\n\nالبسط: $${num} × ${100 / den} = ${ans}$.\n\nإذن $${fr(num, den)} = ${ans}${PC}$ ✔️`,
  }
}

// كسر إلى نسبة بالتقريب
const roundQ = (): Question => {
  const den = pick([3, 6, 7, 9, 11, 12, 13, 15]), num = rand(1, den - 1)
  const exact = (num * 100) / den, ans = r2(exact), cut = Math.floor(exact * 100) / 100
  return {
    kind: 'numeric',
    prompt: `اكتبي $${fr(num, den)}$ على صورة نسبة مئوية، وقرّبي لأقرب جزء من مئة (اكتبي العدد بدون الرمز).`,
    answer: ans,
    wrong: wr(ans, [
      { value: cut, why: 'قطعتي الأرقام بدل ما تقرّبي! 😊 انظري للمنزلة الثالثة: ٥ أو أكثر نزيد اللي قبلها.' },
      { value: r3(num / den), why: 'هاد الكسر العشري! 🔍 لازم نضربه بـ١٠٠.' },
      { value: r2(100 / den), why: 'نسيتي تضربي بالبسط! 😅' },
    ]),
    why: `نكتب الكسر عشرياً ونضرب بـ١٠٠:\n\n$${num} ÷ ${den} = ${String(num / den).slice(0, 7).replace('.', '٫')}…$ ثم $× 100 ≈ ${dec2(ans)}$\n\nالنسبة **$${dec2(ans)}${PC}$** ✔️`,
  }
}

// مسألة حياتية
const wordQ = (): Question => {
  const T = pick([8, 11, 13, 15, 16, 20, 25, 32, 40]), part = rand(1, T - 1)
  const exact = (part * 100) / T, ans = r2(exact), cut = Math.floor(exact * 100) / 100
  return {
    kind: 'numeric',
    prompt: `أجابت مها عن $${part}$ سؤالاً من أصل $${T}$ سؤالاً. ما النسبة المئوية للأسئلة التي أجابت عنها؟ قرّبي لأقرب جزء من مئة (اكتبي العدد بدون الرمز).`,
    answer: ans,
    wrong: wr(ans, [
      { value: r2(100 - exact), why: 'هاد نسبة الأسئلة **غير** المجابة! 🔄 السؤال عن اللي أجابت عنها.' },
      { value: r3(part / T), why: 'هاد الكسر العشري! 🔍 نضربه بـ١٠٠.' },
      { value: cut, why: 'قطعتي الأرقام بدل ما تقرّبي! 😊' },
    ]),
    why: `الكسر: $${fr(part, T)}$ ← $${part} ÷ ${T} × 100 ≈ ${dec2(ans)}$\n\nالنسبة **$${dec2(ans)}${PC}$** ✔️`,
  }
}

