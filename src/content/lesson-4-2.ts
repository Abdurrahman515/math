import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { dec, dec2, r2, r3 } from '../lib/dec'

const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// معدل الوحدة بالقسمة
const unitRateQ = (): Question => {
  const r = rand(4, 40) / 2, n = rand(2, 9), T = r * n
  const text = pick([
    `قطعت سيارة $${dec(T)}$ كلم في $${n}$ ساعات بسرعة ثابتة. كم كيلومتراً تقطع في الساعة الواحدة؟`,
    `تقاضى عامل $${dec(T)}$ ريالاً لقاء عمله $${n}$ ساعات. ما أجرته في الساعة الواحدة بالريال؟`,
    `ثمن $${n}$ كيلوجرامات من التمر $${dec(T)}$ ريالاً. ما ثمن الكيلوجرام الواحد بالريال؟`,
  ])
  return {
    kind: 'numeric',
    prompt: text,
    answer: r,
    wrong: wr(r, [
      { value: r3(T * n), why: 'ضربتي! 😅 معدل الوحدة بنطلعه **بالقسمة**: الكمية ÷ العدد.' },
      { value: r3(T - n), why: 'هاد طرح! المعدل نسبة بين كميتين فنقسم 💡' },
      { value: r3(n / T), why: 'قلبتي القسمة! 🔄 نقسم على اللي بدنا نخلّيه **١** (العدد المقابل).' },
    ]),
    why: `المعدل: $${dec(T)}$ لكل $${n}$.\n\nنقسم البسط والمقام على $${n}$ ليصير المقام ١:\n\n$${dec(T)} ÷ ${n} = ${dec(r)}$\n\nمعدل الوحدة = $${dec(r)}$ ✔️`,
  }
}

// تقريب معدل الوحدة لأقرب جزء من مئة
const roundRateQ = (): Question => {
  const n = pick([3, 6, 7, 9]), T = rand(5, 60)
  if (T % n === 0) return roundRateQ()
  const exact = T / n
  const ans = r2(exact)
  const cut = Math.floor(exact * 100) / 100
  return {
    kind: 'numeric',
    prompt: `اشترت هدى $${n}$ دفاتر بمبلغ $${T}$ ريالاً. ما ثمن الدفتر الواحد؟ قرّبي الناتج لأقرب جزء من مئة.`,
    answer: ans,
    wrong: wr(ans, [
      { value: cut, why: 'قطعتي الأرقام بدل ما تقرّبي! 😊 انظري للمنزلة الثالثة: إذا كانت ٥ أو أكثر نزيد المنزلة قبلها.' },
      { value: r3(Math.round(exact * 10) / 10), why: 'قرّبتي لأقرب جزء من **عشرة** بس! نريد منزلتين بعد الفاصلة 🔍' },
      { value: r3(T * n), why: 'ضربتي! المعدل بنطلعه بالقسمة 💡' },
    ]),
    why: `$${T} ÷ ${n} = ${String(exact).slice(0, 7).replace('.', '٫')}…$\n\nنقرّب لأقرب جزء من مئة: **$${dec2(ans)}$** ريال.`,
  }
}

// أيهما أوفر؟
const bestBuyQ = (): Question => {
  let u1: number, u2: number
  do { u1 = rand(2, 9); u2 = rand(2, 9) } while (u1 === u2)
  const s1 = rand(2, 8), s2 = rand(2, 8)
  const P1 = s1 * u1, P2 = s2 * u2
  const betterFirst = u1 < u2
  const what = pick(['تمر', 'أرز', 'حليب بالتر', 'عصير بالتر'])
  const unit = what.includes('تر') ? 'لترات' : 'كيلوجرامات'
  return {
    kind: 'choice',
    prompt: `يعرض محل ${what.replace(' بالتر', '')} بعبوتين: الأولى $${s1}$ ${unit} بـ$${P1}$ ريالاً، والثانية $${s2}$ ${unit} بـ$${P2}$ ريالاً. أيهما أوفر (سعر الوحدة فيها أقل)؟`,
    options: [
      { text: 'العبوة الأولى', correct: betterFirst,
        why: betterFirst
          ? `برافو! سعر الوحدة فيها $${P1} ÷ ${s1} = ${u1}$ مقابل $${u2}$ بالتانية ✔️🎉`
          : `قارنتي بالمبلغ الكلي؟ 🤔 سعر الوحدة بالأولى $${u1}$ وبالتانية $${u2}$، فالتانية أوفر.` },
      { text: 'العبوة الثانية', correct: !betterFirst,
        why: !betterFirst
          ? `ممتاز! سعر الوحدة فيها $${P2} ÷ ${s2} = ${u2}$ مقابل $${u1}$ بالأولى ✔️⭐`
          : `قارنتي بالمبلغ الكلي؟ 🤔 سعر الوحدة بالأولى $${u1}$ وبالتانية $${u2}$، فالأولى أوفر.` },
    ],
  }
}

// استعمال معدل الوحدة
const usingRateQ = (): Question => {
  const r = rand(2, 9), t1 = rand(2, 6), t2 = t1 + rand(3, 9)
  const n1 = r * t1, ans = r * t2
  return {
    kind: 'numeric',
    prompt: `تغلّف منال $${n1}$ هدايا في $${t1}$ دقائق. كم هدية تغلّف في $${t2}$ دقيقة إذا استمرت بنفس المعدل؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: r, why: 'هاد معدل الوحدة بس! 😊 لسا لازم نضربه بعدد الدقائق المطلوبة.' },
      { value: n1 * t2, why: 'ضربتي الهدايا بالدقائق الجديدة مباشرة! 😅 لازم نجيب معدل الوحدة أول.' },
      { value: n1 + t2 - t1, why: 'الجمع ما بيمشي هون! الكميات **متناسبة** 💡' },
    ]),
    why: `معدل الوحدة: $${n1} ÷ ${t1} = ${r}$ هدية بالدقيقة.\n\nنضربه بعدد الدقائق: $${r} × ${t2} = ${ans}$ هدية ✔️`,
  }
}

