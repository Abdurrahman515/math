const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

const SCENES: [string, string, string, string][] = [
  ['سلة فواكه', 'حبات التفاح', 'حبات البرتقال', 'الفاكهة'],
  ['الصف الأول المتوسط', 'البنات', 'الأولاد', 'الطلاب'],
  ['حقيبة سلمى', 'الأقلام الزرقاء', 'الأقلام الحمراء', 'الأقلام'],
  ['مكتبة البيت', 'الكتب العلمية', 'الكتب الأدبية', 'الكتب'],
]

// نسبة جزء إلى كل
const partWholeQ = (): Question => {
  let a: number, b: number
  do { a = rand(1, 7); b = rand(1, 7) } while (a === b || gcd(a, b) !== 1)
  const k = rand(2, 6), x = a * k, y = b * k
  const [place, A, B, tot] = pick(SCENES)
  return {
    kind: 'choice',
    prompt: `في ${place} $${x}$ من ${A} و$${y}$ من ${B}. ما نسبة ${A} إلى **جميع** ${tot} في أبسط صورة؟`,
    options: [
      { text: `$${a} : ${a + b}$`, correct: true,
        why: `برافو! المجموع $${x} + ${y} = ${x + y}$، ونسبة $${x} : ${x + y}$ بعد القسمة على $${k}$ بتصير $${a} : ${a + b}$ ✔️🎉` },
      { text: `$${a} : ${b}$`, why: 'هاد **جزء إلى جزء**! السؤال بيقارن بالمجموع كله 🔍' },
      { text: `$${b} : ${a + b}$`, why: `قلبتي الأجزاء! نريد ${A} بالأول، مو ${B} 😊` },
      { text: `$${x} : ${x + y}$`, why: 'الجواب صحيح، بس مو **بأبسط صورة**! جرّبي تقسمي الطرفين على قاسمهم المشترك الأكبر 💡' },
    ],
  }
}

// هل النسبتان متكافئتان؟
const equivCheckQ = (): Question => {
  let p: number, q: number
  do { p = rand(1, 9); q = rand(1, 9) } while (p === q || gcd(p, q) !== 1)
  const k1 = rand(2, 5)
  let k2: number
  do { k2 = rand(2, 7) } while (k2 === k1)
  const same = rand(0, 1) === 1
  const x1 = p * k1, y1 = q * k1, x2 = p * k2, y2 = same ? q * k2 : q * k2 + rand(1, 2)
  const g2 = gcd(x2, y2)
  const first = `$${x1}$ صفحة في $${y1}$ دقيقة`
  const second = `$${x2}$ صفحة في $${y2}$ دقيقة`
  return {
    kind: 'choice',
    prompt: `تقرأ ليلى ${first}، وتقرأ ريم ${second}. هل النسبتان متكافئتان؟`,
    options: [
      { text: 'نعم، متكافئتان', correct: same,
        why: same
          ? `برافو! الاثنتان بتتبسّطان إلى $${p} : ${q}$ ✔️🎉`
          : `لا يا ذكية 🤔 الأولى بتتبسّط إلى $${p} : ${q}$، والتانية إلى $${x2 / g2} : ${y2 / g2}$ وهنّي مختلفتين.` },
      { text: 'لا، غير متكافئتين', correct: !same,
        why: !same
          ? `ممتاز! الأولى $${p} : ${q}$ والتانية $${x2 / g2} : ${y2 / g2}$، مختلفتين ✔️⭐`
          : `قريبة! لكن الاثنتين بتتبسّطان لنفس النسبة $${p} : ${q}$، يعني متكافئتان 🔍` },
    ],
  }
}

// إيجاد الحد الناقص
const missingTermQ = (): Question => {
  let a: number, b: number
  do { a = rand(2, 9); b = rand(2, 9) } while (a === b)
  const k = rand(2, 7), c = a * k, ans = b * k
  return {
    kind: 'numeric',
    prompt: `النسبتان $${a} : ${b}$ و$${c} : ن$ متكافئتان. ما قيمة $ن$؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: b + c - a, why: `جمعتي نفس العدد على الحدّين! 😅 بنطلع من $${a}$ لـ$${c}$ بالضرب بـ$${k}$، فنضرب $${b}$ بـ$${k}$ كمان.` },
      { value: c, why: 'هاد الحد الأول نفسه! دورنا على الحد التاني 🔍' },
      { value: a * c, why: 'عامل الضرب هو العدد اللي بيربط $' + a + '$ بـ$' + c + '$، مو الحدّين مع بعض 💡' },
    ]),
    why: `نبحث عن العامل اللي بيربط $${a}$ بـ$${c}$: $${a} × ${k} = ${c}$.\n\nنضرب الحد التاني بنفس العامل: $${b} × ${k} = ${ans}$.\n\nتحقق: $${a} : ${b}$ و$${c} : ${ans}$ لهن نفس القيمة ✔️`,
  }
}

