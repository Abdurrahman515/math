import type { Lesson, Question } from '../types'
import { evaluate, trace } from '../lib/calc'
import { rand } from '../lib/rng'

const orderQ = (): Question => {
  const kind = rand(0, 2)
  let expr: string, naive: number, hint: string
  if (kind === 0) {
    const a = rand(2, 9), b = rand(2, 9), c = rand(2, 9)
    expr = `${a} + ${b} × ${c}`
    naive = (a + b) * c
    hint = `جمعتي أول لأنو جاي أول بالكتابة. بس الضرب بيسبق الجمع! لازم نحسب $${b} × ${c}$ قبل.`
  } else if (kind === 1) {
    const a = rand(2, 6), b = rand(2, 6), c = rand(2, 6), d = rand(2, 6)
    expr = `${a} × ${b} + ${c} × ${d}`
    naive = (a * b + c) * d
    hint = `مشيتي من اليسار لليمين بدون ما تراعي الترتيب. الضربتين ($${a} × ${b}$ و $${c} × ${d}$) لازم يصيروا قبل الجمع.`
  } else {
    const a = rand(2, 6), b = rand(2, 6), c = rand(2, 6), d = rand(1, 7)
    expr = `(${a} + ${b}) × ${c} − ${d}`
    naive = a + b * c - d
    hint = `تجاهلتي الأقواس. اللي جوّا الأقواس بيتحسب أول: $${a} + ${b} = ${a + b}$.`
  }
  const answer = evaluate(expr)
  return {
    kind: 'numeric',
    prompt: `احسبي: $${expr}$`,
    answer,
    wrong: naive === answer ? [] : [{ value: naive, why: hint }],
    why: trace(expr).map((s) => `$${s}$`).join('  ←  '),
    fallback: 'مو هيك. تذكري: ( ) أول، بعدين القوى، بعدين × ÷، وآخر شي + −',
  }
}

