import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { dec, dec2, fr, r2, r3 } from '../lib/dec'

const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}
const mn = (k: number) => (k === 1 ? 'منزلة واحدة' : `${k} منازل`)

const MET = [
  { big: 'كيلومترات', small: 'أمتار', f: 1000, k: 3 },
  { big: 'أمتار', small: 'سنتمترات', f: 100, k: 2 },
  { big: 'أمتار', small: 'ملمترات', f: 1000, k: 3 },
  { big: 'لترات', small: 'مللترات', f: 1000, k: 3 },
  { big: 'كيلوجرامات', small: 'جرامات', f: 1000, k: 3 },
  { big: 'سنتمترات', small: 'ملمترات', f: 10, k: 1 },
]

// ماذا نفعل؟
const opQ = (): Question => {
  const u = pick(MET), down = rand(0, 1) === 1
  const from = down ? u.big : u.small, to = down ? u.small : u.big
  const mul = (f: number, k: number) => `نضرب في $${f}$ (نحرّك الفاصلة ${mn(k)} لليمين)`
  const div = (f: number, k: number) => `نقسم على $${f}$ (نحرّك الفاصلة ${mn(k)} لليسار)`
  return {
    kind: 'choice',
    prompt: `للتحويل من ${from} إلى ${to}، ماذا نفعل؟`,
    options: [
      { text: down ? mul(u.f, u.k) : div(u.f, u.k), correct: true,
        why: `برافو! 🎉 ${down ? 'من وحدة كبيرة لصغيرة بيكبر العدد فنضرب' : 'من وحدة صغيرة لكبيرة بيصغر العدد فنقسم'} ✔️` },
      { text: down ? div(u.f, u.k) : mul(u.f, u.k), why: 'قلبتي الاتجاه! 🔄 فكّري: العدد لازم يكبر ولا يصغر؟' },
      { text: down ? mul(u.f * 10, u.k + 1) : div(u.f * 10, u.k + 1), why: 'زدتي صفراً زيادة! 😅 عدّي الأصفار اللي بالعلاقة بدقة.' },
      { text: `نجمع $${u.f}$`, why: 'التحويل بين الوحدات بالضرب أو بالقسمة، مو بالجمع 💡' },
    ],
  }
}

// من أكبر إلى أصغر
const toSmallQ = (): Question => {
  const u = pick(MET), t = rand(11, 99), n = t / 10, ans = (t * u.f) / 10
  return {
    kind: 'numeric',
    prompt: `حوّلي $${dec(n)}$ ${u.big} إلى ${u.small}.`,
    answer: ans,
    wrong: wr(ans, [
      { value: r3(ans * 10), why: `زدتي صفراً زيادة! 😅 الضرب بـ$${u.f}$ يعني نحرّك الفاصلة ${mn(u.k)} بالضبط.` },
      { value: r3(ans / 10), why: `حرّكتي الفاصلة أقل من اللازم! 🔍 لازم ${mn(u.k)}.` },
      { value: r3(n / u.f), why: 'قسمتي! 🔄 لما نروح من وحدة كبيرة لصغيرة، العدد بيكبر.' },
    ]),
    why: `نضرب بقوة العدد ١٠ المناسبة: $${dec(n)} × ${u.f} = ${dec(ans)}$ ${u.small} ✔️`,
  }
}

// من أصغر إلى أكبر
const toLargeQ = (): Question => {
  const u = pick(MET), t = rand(11, 99), x = (t * u.f) / 10, ans = t / 10
  return {
    kind: 'numeric',
    prompt: `حوّلي $${dec(x)}$ ${u.small} إلى ${u.big}.`,
    answer: ans,
    wrong: wr(ans, [
      { value: r3(ans * 10), why: `حرّكتي الفاصلة أقل من اللازم! 🔍 لازم ${mn(u.k)} لليسار.` },
      { value: r3(ans / 10), why: 'حرّكتي الفاصلة منزلة زيادة! 😅 عدّي الأصفار بدقة.' },
      { value: x * u.f, why: 'ضربتي! 🔄 لما نروح من وحدة صغيرة لكبيرة، العدد بيصغر فنقسم.' },
    ]),
    why: `نقسم على $${u.f}$: $${dec(x)} ÷ ${u.f} = ${dec(ans)}$ ${u.big} ✔️`,
  }
}

// من إنجليزي إلى متري
const ENG = [
  { from: 'بوصة', fromPl: 'بوصة', to: 'سنتمتر', r: 2.54, unitTo: 'سم', max: 30 },
  { from: 'ياردة', fromPl: 'ياردات', to: 'متر', r: 0.91, unitTo: 'م', max: 20 },
  { from: 'ميل', fromPl: 'أميال', to: 'كيلومتر', r: 1.61, unitTo: 'كلم', max: 20 },
  { from: 'رطل', fromPl: 'أرطال', to: 'كيلوجرام', r: 0.4536, unitTo: 'كجم', max: 20 },
  { from: 'جالون', fromPl: 'جالونات', to: 'لتر', r: 3.79, unitTo: 'ل', max: 15 },
]
const engMetricQ = (): Question => {
  const u = pick(ENG), n = rand(3, u.max), exact = n * u.r, ans = r2(exact)
  const cut = Math.floor(exact * 100) / 100
  return {
    kind: 'numeric',
    prompt: `١ ${u.from} ≈ $${dec(u.r)}$ ${u.unitTo}. حوّلي $${n}$ ${u.fromPl} إلى ${u.to} تقريباً، وقرّبي لأقرب جزء من مئة.`,
    answer: ans,
    wrong: wr(ans, [
      { value: cut, why: 'قطعتي الأرقام بدل ما تقرّبي! 😊 انظري للمنزلة الثالثة: ٥ أو أكثر نزيد اللي قبلها.' },
      { value: r2(n / u.r), why: 'قسمتي! 🔄 كل ١ ' + u.from + ' بيساوي ' + dec(u.r) + ' ' + u.unitTo + '، فنضرب.' },
      { value: r2(n + u.r), why: 'هاد جمع! نضرب بمعدل الوحدة 💡' },
    ]),
    why: `نضرب: $${n} × ${dec(u.r)} = ${dec(r3(exact))}$\n\nنقرّب لأقرب جزء من مئة: **$${dec2(ans)}$** ${u.unitTo} ✔️`,
  }
}

