import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'

const LET = ['س', 'ص', 'ن', 'ع', 'ك']

const exprQ = (): Question => {
  const v = pick(LET), k = rand(2, 9)
  const V = `$${v}$`, K = `$${k}$`
  const T = [
    { p: `مجموع العدد ${V} والعدد ${K}`, ok: `${v} + ${k}`,
      bad: [[`${v} − ${k}`, 'هاد طرح، و"مجموع" يعني **جمع**.'], [`${k}${v}`, 'هاد ضرب، و"مجموع" يعني **جمع**.']] },
    { p: `${K} أقل من العدد ${V}`, ok: `${v} − ${k}`,
      bad: [[`${k} − ${v}`, `عكستي الترتيب! "${K} أقل من ${V}" يعني منطرح ${K} **من** ${V}.`], [`${v} + ${k}`, 'هاد جمع، و"أقل من" يعني **طرح**.']] },
    { p: `زاد العدد ${V} بمقدار ${K}`, ok: `${v} + ${k}`,
      bad: [[`${v} − ${k}`, '"زاد" يعني **جمع** مو طرح.'], [`${k} − ${v}`, 'ما في طرح هون: "زاد" بتدل على جمع.']] },
    { p: `${K} أمثال العدد ${V}`, ok: `${k}${v}`,
      bad: [[`${k} + ${v}`, '"أمثال" يعني **ضرب** مو جمع.'], [`${v} ÷ ${k}`, '"أمثال" يعني **ضرب** مو قسمة.']] },
    { p: `ناتج قسمة العدد ${V} على ${K}`, ok: `${v} ÷ ${k}`,
      bad: [[`${k} ÷ ${v}`, `عكستي! منقسم ${V} **على** ${K}.`], [`${v} − ${k}`, 'هاد طرح، والمطلوب **قسمة**.']] },
    { p: `نصف العدد ${V}`, ok: `${v} ÷ 2`,
      bad: [[`2${v}`, 'هاد **ضعف** العدد مو نصفه.'], [`${v} − 2`, '"نصف" يعني قسمة على ٢.']] },
  ]
  const t = pick(T)
  return {
    kind: 'choice',
    prompt: `اكتبي العبارة الجبرية: ${t.p}`,
    options: [
      { text: `$${t.ok}$`, correct: true, why: 'صح عليكِ! ترجمتي الجملة لعبارة جبرية 🎉' },
      ...t.bad.map(([e, why]) => ({ text: `$${e}$`, why })),
    ],
  }
}

const eqQ = (): Question => {
  const v = pick(LET), a = rand(2, 9), b = rand(10, 40)
  const V = `$${v}$`, A = `$${a}$`, B = `$${b}$`
  const forms: Record<string, string> = {
    sub: `${v} − ${a} = ${b}`, add: `${v} + ${a} = ${b}`, mul: `${a}${v} = ${b}`,
    div: `${v} ÷ ${a} = ${b}`, rev: `${a} − ${v} = ${b}`,
  }
  const T = [
    { p: `أقل من العدد ${V} بـ ${A} يساوي ${B}`, k: 'sub', bad: ['rev', 'add', 'mul'] },
    { p: `أكثر من العدد ${V} بـ ${A} يساوي ${B}`, k: 'add', bad: ['sub', 'rev', 'mul'] },
    { p: `${A} أمثال العدد ${V} يساوي ${B}`, k: 'mul', bad: ['add', 'div', 'sub'] },
    { p: `ناتج قسمة العدد ${V} على ${A} يساوي ${B}`, k: 'div', bad: ['mul', 'sub', 'add'] },
  ]
  const t = pick(T)
  const WHY: Record<string, string> = {
    rev: 'عكستي الترتيب! "أقل من العدد س" معناها س هو اللي بيتنقّص منه.',
    add: 'هاد جمع، والجملة فيها كلمة بتدل على عملية تانية.',
    sub: 'هاد طرح، والجملة فيها كلمة بتدل على عملية تانية.',
    mul: 'هاد ضرب، والجملة فيها كلمة بتدل على عملية تانية.',
    div: 'هاد قسمة، والجملة فيها كلمة بتدل على عملية تانية.',
  }
  return {
    kind: 'choice',
    prompt: `اكتبي المعادلة: ${t.p}`,
    options: [
      { text: `$${forms[t.k]}$`, correct: true, why: 'صح! حوّلتي الكلمات لعمليات وكلمة "يساوي" لإشارة (=).' },
      ...t.bad.map((k) => ({ text: `$${forms[k]}$`, why: WHY[k] })),
    ],
  }
}

const storyQ = (): Question => {
  const a = rand(2, 9), b = rand(5, 30)
  const F = [
    { k: 'add', eq: `س + ${a} = ${b}`, s: `كان مع سلمى مبلغ، فأضافت إليه $${a}$ ريالاً فصار معها $${b}$ ريالاً. س تمثّل المبلغ الذي كان معها في البداية.` },
    { k: 'sub', eq: `س − ${a} = ${b}`, s: `كان مع سلمى مبلغ، أنفقت منه $${a}$ ريالاً فبقي معها $${b}$ ريالاً. س تمثّل المبلغ الذي كان معها في البداية.` },
    { k: 'mul', eq: `${a}س = ${b}`, s: `اشترت سلمى $${a}$ أقلام بالسعر نفسه ودفعت $${b}$ ريالاً. س تمثّل ثمن القلم الواحد.` },
    { k: 'div', eq: `س ÷ ${a} = ${b}`, s: `وزّعت سلمى مبلغاً بالتساوي على $${a}$ صديقات فأخذت كل واحدة $${b}$ ريالاً. س تمثّل المبلغ الذي وزّعته.` },
  ]
  const target = pick(F)
  return {
    kind: 'choice',
    prompt: `أي المسائل الآتية يمكن التعبير عنها بالمعادلة $${target.eq}$ ؟`,
    options: F.map((f) => ({
      text: f.s,
      correct: f.k === target.k,
      why: f.k === target.k
        ? `صح! هاي المسألة بتُمثَّل بالمعادلة $${f.eq}$.`
        : `هاي المسألة بتُمثَّل بالمعادلة $${f.eq}$ مو $${target.eq}$.`,
    })),
  }
}

