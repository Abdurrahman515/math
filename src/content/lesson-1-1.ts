import type { Lesson, Question } from '../types'
import { rand } from '../lib/rng'

const seqQ = (): Question => {
  const start = rand(2, 9), step = rand(2, 6)
  const seq = [0, 1, 2, 3].map((i) => start + i * step)
  const ans = seq[3] + step
  return {
    kind: 'numeric',
    prompt: `شو العدد اللي بعده بالنمط؟\n$${seq.join(', ')}, ?$`,
    answer: ans,
    wrong: [
      { value: ans + 1, why: `ضفتي ${step + 1} بدل ${step}. شوفي الفرق بين أي عددين متجاورين: كلو ${step}.` },
      { value: ans - 1, why: `ضفتي ${step - 1} بدل ${step}. شوفي الفرق بين أي عددين متجاورين: كلو ${step}.` },
    ],
    why: `الفرق بين كل عددين متجاورين ثابت = ${step}، يعني $${seq[3]} + ${step} = ${ans}$`,
  }
}

