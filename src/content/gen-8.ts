export function crossAngleQ(): Question {
  const m = one([30, 40, 50, 60, 70, 80, 100, 110, 120, 130, 140, 150])
  const ask = one([2, 3, 4])
  const adj = ask !== 3
  const ans = adj ? 180 - m : m
  return num(
    `تقاطع مستقيمان وتكوّنت ٤ زوايا مرقّمة ١، ٢، ٣، ٤ بالترتيب حول نقطة التقاطع. إذا كان ق∠١ = ${m}°، فما ق∠${ask}؟`,
    ans,
    adj
      ? `∠${ask} متجاورة مع ∠١ وبيشكّلوا زاوية مستقيمة: ١٨٠ − ${m} = ${ans}° ✔️`
      : `∠٣ مقابلة بالرأس لـ∠١، والمتقابلتان بالرأس متطابقتان: ${m}° ✔️`,
    adj
      ? [[m, `هاي قياس ∠١ نفسها 🔍 ∠${ask} متجاورة معها مش مقابلة، فالاتنين مجموعهم ١٨٠°.`]]
      : [[180 - m, `هاد قياس زاوية متجاورة 🔍 ∠٣ مقابلة بالرأس لـ∠١ فلها نفس قياسها.`]],
  )
}

