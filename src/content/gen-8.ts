const ch = (prompt: string, ok: [string, string], bad: [string, string][]): Question => ({
  kind: 'choice',
  prompt,
  options: [{ text: ok[0], correct: true, why: ok[1] }, ...bad.map(([text, why]): ChoiceOption => ({ text, why }))],
})

/** أخطاء شائعة بلا تكرار ولا تطابق مع الجواب الصحيح */
const wr = (answer: number, list: [number, string][]) => {
  const seen = new Set<number>([answer])
  const out: { value: number; why: string }[] = []
  for (const [value, why] of list) {
    if (value > 0 && Number.isFinite(value) && !seen.has(value)) {
      seen.add(value)
      out.push({ value, why })
    }
  }
  return out
}
const num = (prompt: string, answer: number, why: string, list: [number, string][] = []): Question => ({
  kind: 'numeric', prompt, answer, why, wrong: wr(answer, list),
})

