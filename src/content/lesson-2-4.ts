import type { Lesson, Question } from '../types'
import { rand } from '../lib/rng'
import { sg } from '../lib/int'

const nz = () => rand(1, 15) * (rand(0, 1) ? 1 : -1)
const term = (n: number) => (n < 0 ? `(${sg(n)})` : String(n))
const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

const sumQ = (): Question => {
  const same = rand(0, 1) === 1
  const A = rand(1, 15), B = rand(1, 15)
  const s = rand(0, 1) ? 1 : -1
  const a = s * A
  const b = same ? s * B : -s * B
  const ans = a + b
  const big = A >= B ? 'الأول' : 'التاني'
  return {
    kind: 'numeric',
    prompt: `أوجدي ناتج $${sg(a)} + ${term(b)}$`,
    answer: ans,
    wrong: wr(ans, same
      ? [
          { value: s * (A - B), why: 'الإشارتين **نفسها**! منجمع القيم المطلقة، مو منطرحها.' },
          { value: -ans, why: 'الإشارة غلط: لما العددين من نفس الإشارة، الناتج بياخد نفس إشارتهم.' },
        ]
      : [
          { value: (A >= B ? s : -s) * (A + B), why: 'الإشارتين **مختلفة**! منطرح القيم المطلقة، مو منجمعها.' },
          { value: -ans, why: 'إشارة الناتج هي إشارة العدد **الأبعد عن الصفر** (الأكبر بالقيمة المطلقة).' },
        ]),
    why: same
      ? `نفس الإشارة: منجمع القيم المطلقة $${A} + ${B} = ${A + B}$ ونحط نفس الإشارة ← $${sg(ans)}$`
      : A === B
        ? `هدول نظيران جمعيان! $${A}$ و $−${A}$ بيلغوا بعض ← $0$`
        : `إشارتين مختلفتين: منطرح القيم المطلقة $${Math.max(A, B)} − ${Math.min(A, B)} = ${Math.abs(ans)}$ وإشارة الناتج إشارة العدد ${big} (الأكبر بالقيمة المطلقة) ← $${sg(ans)}$`,
  }
}

const inverseQ = (): Question => {
  const k = nz()
  return {
    kind: 'choice',
    prompt: `ما النظير الجمعي للعدد $${sg(k)}$ ؟`,
    options: [
      { text: `$${sg(-k)}$`, correct: true, why: `$${sg(k)} + (${sg(-k)}) = 0$ ✓ مجموعهم صفر.` },
      { text: `$${sg(k)}$`, why: 'هاد نفس العدد! النظير الجمعي هو اللي لما نجمعه مع العدد بيعطي **صفر**.' },
      { text: '$0$', why: 'الصفر بس نظير نفسه. لازم عدد لما نجمعه مع العدد يطلع صفر.' },
    ],
  }
}

const missingQ = (): Question => {
  const a = nz()
  return {
    kind: 'numeric',
    prompt: `أوجدي العدد الناقص: $${sg(a)} + ● = 0$`,
    answer: -a,
    wrong: wr(-a, [{ value: a, why: `$${sg(a)} + ${term(a)} = ${sg(2 * a)}$ مو صفر! لازم العدد المعاكس.` }]),
    why: `النظير الجمعي لـ $${sg(a)}$ هو $${sg(-a)}$`,
  }
}

const groupQ = (): Question => {
  const x = rand(2, 15), y = nz()
  return {
    kind: 'numeric',
    prompt: `احسبي ذهنياً (جمّعي النظيرين أول): $${x} + ${term(y)} + (${sg(-x)})$`,
    answer: y,
    why: `$${x} + (${sg(-x)}) = 0$ فبيضل $${sg(y)}$`,
    fallback: 'دوّري على عددين نظيرين جمعيين (مجموعهم صفر)، واجمعيهم أول.',
  }
}

const tempQ = (): Question => {
  const t = rand(5, 20), d = rand(2, 9), u = rand(1, 9)
  const ans = t - d + u
  return {
    kind: 'numeric',
    prompt: `كانت درجة الحرارة $${t}$ ثم انخفضت $${d}$ درجات وبعدها ارتفعت $${u}$ درجات. كم صارت الدرجة؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: t + d + u, why: `الانخفاض **بينقص**: الجملة هي $${t} + (−${d}) + ${u}$.` },
      { value: t - d - u, why: 'الارتفاع **بيزيد** مو بينقص.' },
    ]),
    why: `$${t} + (−${d}) + ${u} = ${ans}$`,
  }
}

