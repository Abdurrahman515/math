import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { sg } from '../lib/int'

const LET = ['س', 'ص', 'ن', 'ع', 'ك', 'م']
const coef = (a: number, v: string) => (a < 0 ? `−${-a}${v}` : `${a}${v}`)
const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}
const nzv = (m: number) => rand(2, m) * (rand(0, 1) ? 1 : -1)

// حلّ معادلة بخطوتين
const twoStepQ = (): Question => {
  const v = pick(LET)
  const a = pick([2, 3, 4, 5, 6, 7, 8, 9]) * (rand(0, 3) === 0 ? -1 : 1)
  const b = rand(1, 12) * (rand(0, 1) ? 1 : -1)
  const ans = nzv(8)
  const c = a * ans + b
  const wrong = [{ value: c - b, why: `وقفتي بنص الطريق! بعد ما تخلّصتي من ${b > 0 ? 'الجمع' : 'الطرح'} لسا لازم نقسم على $${sg(a)}$.` }]
  if ((c + b) % a === 0) {
    wrong.push({ value: (c + b) / a, why: `عكستي عملية ${b > 0 ? 'الجمع' : 'الطرح'}! ${b > 0 ? 'نطرح' : 'نضيف'} $${Math.abs(b)}$ مو العكس.` })
  }
  wrong.push({ value: -ans, why: `انتبهي للإشارة عند القسمة على $${sg(a)}$: عددان إشارتيهم **مختلفة** ناتجهم سالب، و**متشابهة** موجب.` })
  return {
    kind: 'numeric',
    prompt: `حلّي المعادلة $${coef(a, v)} ${b < 0 ? '−' : '+'} ${Math.abs(b)} = ${sg(c)}$ ثم اكتبي قيمة $${v}$.`,
    answer: ans,
    wrong: wr(ans, wrong),
    why: `نتخلّص من ${b > 0 ? 'الجمع' : 'الطرح'} أول: ${b > 0 ? `نطرح $${b}$` : `نضيف $${-b}$`} من الطرفين فيصير $${coef(a, v)} = ${sg(c - b)}$.\n\nبعدين نقسم على $${sg(a)}$: $${v} = ${sg(ans)}$.\n\nتحقق: $${sg(a)} × ${ans < 0 ? `(${sg(ans)})` : ans} ${b > 0 ? '+' : '−'} ${Math.abs(b)} = ${sg(c)}$ ✔️`,
  }
}

// ما الخطوة الأولى؟
const firstStepQ = (): Question => {
  const v = pick(LET)
  const a = rand(2, 9), b = rand(1, 15) * (rand(0, 1) ? 1 : -1)
  const c = a * rand(2, 9) + b
  const pre = b > 0 ? `نطرح $${b}$ من الطرفين` : `نضيف $${-b}$ للطرفين`
  const opp = b > 0 ? `نضيف $${b}$ للطرفين` : `نطرح $${-b}$ من الطرفين`
  return {
    kind: 'choice',
    prompt: `ما الخطوة **الأولى** المناسبة (بحسب الترتيب الأسهل الذي تعلمناه) لحلّ المعادلة $${a}${v} ${b < 0 ? '−' : '+'} ${Math.abs(b)} = ${c}$ ؟`,
    options: [
      { text: pre, correct: true, why: `صح! بنتخلّص من ${b > 0 ? 'الجمع' : 'الطرح'} أول، وبعدين نقسم على $${a}$ ✔️` },
      { text: `نقسم الطرفين على $${a}$`,
        why: 'مو غلط رياضياً، بس لازم نقسم **كل** الحدود وبتطلع كسور. الطريقة الأسهل: نتخلّص من الجمع أو الطرح أول.' },
      { text: opp, why: `هيك بتكبّر الحد الثابت بدل ما تتخلّصي منه. عكس ${b > 0 ? 'الجمع' : 'الطرح'} هو ${b > 0 ? 'الطرح' : 'الجمع'}.` },
      { text: `نضرب الطرفين في $${a}$`, why: 'الضرب بيكبّر المعامل. عكس الضرب هو **القسمة**.' },
    ],
  }
}

// مسألة حياتية بخطوتين
const storyTwoQ = (): Question => {
  const u = rand(2, 8), f = rand(2, 12), n = rand(3, 12), T = u * n + f
  const S = [
    { s: `يأخذ بائع أزهار $${u}$ ريالات ثمناً للزهرة الواحدة، و$${f}$ ريالات بدل تنسيق الباقة وتغليفها. إذا كان معك $${T}$ ريالاً، فكم زهرة يمكنك أن تشتري؟` },
    { s: `مركز لياقة يأخذ $${f}$ ريالاً رسم اشتراك مرة واحدة، و$${u}$ ريالات كل شهر. إذا كان معك $${T}$ ريالاً، فكم شهراً تستطيعين الاشتراك؟` },
    { s: `مع صلاح $${f}$ ريالاً، ويوفّر $${u}$ ريالات كل أسبوع. بعد كم أسبوعاً يصير معه $${T}$ ريالاً؟` },
    { s: `تدفعين $${f}$ ريالاً شهرياً اشتراكاً ثابتاً، و$${u}$ ريالات عن كل جيجابايت إضافي. إذا كانت فاتورتك $${T}$ ريالاً، فكم جيجابايت إضافياً استعملتِ؟` },
  ]
  const wrong = [{ value: T - f, why: 'وقفتي بنص الطريق! بعد ما نطرح الثابت لازم نقسم على السعر المتكرر.' }]
  if ((T + f) % u === 0) wrong.push({ value: (T + f) / u, why: 'الثابت **بينزاد** على المجموع، فبنرجّعه بالطرح مو بالجمع.' })
  return {
    kind: 'numeric',
    prompt: pick(S).s,
    answer: n,
    wrong: wr(n, wrong),
    why: `المعادلة: $${u}ن + ${f} = ${T}$\n\nنطرح $${f}$ من الطرفين: $${u}ن = ${T - f}$\n\nنقسم على $${u}$: $ن = ${n}$\n\nتحقق: $${u} × ${n} + ${f} = ${T}$ ✔️`,
  }
}

// أي معادلة تمثّل المسألة
const eqFromStoryQ = (): Question => {
  const u = rand(8, 20), f = rand(10, 30), n = rand(2, 6), T = u * n + f
  return {
    kind: 'choice',
    prompt: `ثمن الكتاب $${u}$ ريالاً، وثمن الحقيبة $${f}$ ريالاً. مع سمير $${T}$ ريالاً ويريد شراء بعض الكتب وحقيبة واحدة. إذا كان $ن$ عدد الكتب، فأي معادلة تمثّل المسألة؟`,
    options: [
      { text: `$${u}ن + ${f} = ${T}$`, correct: true, why: 'صح! الكتب بتتكرر (ضرب)، والحقيبة بتنزاد **مرة وحدة**.' },
      { text: `$(${u} + ${f})ن = ${T}$`, why: 'هيك كأنك بتشتري حقيبة مع **كل** كتاب! الحقيبة واحدة بس.' },
      { text: `$${u} + ${f}ن = ${T}$`, why: 'هيك الحقيبة هي اللي بتتكرر، والمفروض الكتب هي اللي بتتكرر.' },
      { text: `$${u}ن − ${f} = ${T}$`, why: 'ثمن الحقيبة **بينزاد** على ثمن الكتب مو بينطرح منها.' },
    ],
  }
}

