const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// أنفقت مبلغاً ثم أضعافه، وبقي مبلغ
const backMoneyQ = (): Question => {
  const a = rand(2, 9), k = rand(2, 4), r = rand(3, 20)
  const ans = r + k * a + a
  return {
    kind: 'numeric',
    prompt: `كان مع طارق مبلغ من المال، أنفق منه $${a}$ ريالات في المطعم، ثم أنفق $${k}$ أضعاف هذا المبلغ في المكتبة، فبقي معه $${r}$ ريالاً. كم ريالاً كان معه في البداية؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: r + k * a, why: 'نسيتي مبلغ **المطعم**! رجّعي الخطوتين: المكتبة أول، وبعدين المطعم.' },
      { value: r + a, why: `نسيتي المكتبة! أنفق $${k}$ أضعاف $${a}$ مو $${a}$ بس.` },
      { value: r + k + a, why: `"$${k}$ أضعاف $${a}$" يعني $${k} × ${a} = ${k * a}$ مو $${k}$ لحالها.` },
    ]),
    why: `نبدأ من الآخر: بقي $${r}$.\n\nنرجّع خطوة المكتبة: $${k} × ${a} = ${k * a}$ ، فنجمع: $${r} + ${k * a} = ${r + k * a}$.\n\nنرجّع خطوة المطعم: $${r + k * a} + ${a} = ${ans}$.\n\nإذن كان معه $${ans}$ ريالاً.`,
  }
}

// أنفقت مبلغين ثم نصف الباقي
const backHalfQ = (): Question => {
  const a = rand(3, 9), b = rand(3, 9), r = rand(2, 9)
  const ans = 2 * r + a + b
  return {
    kind: 'numeric',
    prompt: `أنفقت مريم $${a}$ ريالات ثمن كراسة، و$${b}$ ريالات ثمن قلم، ونصف ما بقي معها ثمن علبة عصير. وبقي معها $${r}$ ريالاً. كم ريالاً كان معها في البداية؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: r + a + b, why: `نسيتي **النصف**! الـ$${r}$ هي نصف الباقي، فالباقي كان $${2 * r}$.` },
      { value: 2 * (r + a + b), why: 'ضاعفتي كل شي! النصف بس هو اللي بيتضاعف (بالرجوع)، والمبلغين بيتجمعوا كما هم.' },
      { value: 2 * r, why: 'وقفتي بنص الطريق! بعد العصير لسا في الكراسة والقلم لازم نرجّعهم.' },
    ]),
    why: `نبدأ من الآخر: بقي $${r}$ وهي **نصف** الباقي، فقبل العصير كان $${r} × 2 = ${2 * r}$.\n\nنرجّع القلم: $${2 * r} + ${b} = ${2 * r + b}$.\n\nنرجّع الكراسة: $${2 * r + b} + ${a} = ${ans}$.\n\nإذن كان معها $${ans}$ ريالاً.`,
  }
}

// عدد مجهول عليه سلسلة عمليات
const backNumQ = (): Question => {
  const a = rand(2, 9), k = rand(2, 5)
  if (rand(0, 1)) {
    const x = rand(2, 12), T = k * x + a
    return {
      kind: 'numeric',
      prompt: `فكّرت سلمى بعدد، ضربته في $${k}$ ثم أضافت $${a}$ إلى الناتج فصار $${T}$. ما العدد؟`,
      answer: x,
      wrong: wr(x, [
        { value: T - a, why: 'وقفتي بنص الطريق! بعد ما نطرح لسا لازم نرجّع خطوة الضرب بالقسمة.' },
        { value: T + a, why: `آخر عملية كانت **جمع** $${a}$، فبنرجّعها بالطرح مو بالجمع.` },
      ]),
      why: `نبدأ من الآخر: $${T}$.\n\nنرجّع الجمع بالطرح: $${T} − ${a} = ${T - a}$.\n\nنرجّع الضرب بالقسمة: $${T - a} ÷ ${k} = ${x}$.\n\nتحقق: $${x} × ${k} + ${a} = ${T}$ ✔️`,
    }
  }
  const x = a + rand(1, 10), T = k * (x - a)
  return {
    kind: 'numeric',
    prompt: `فكّرت سلمى بعدد، طرحت منه $${a}$ ثم ضربت الناتج في $${k}$ فصار $${T}$. ما العدد؟`,
    answer: x,
    wrong: wr(x, [
      { value: T + a, why: 'ما قسمتي على المعامل! آخر عملية كانت **ضرب**، فأول شي بنرجّع عكسها: القسمة.' },
      { value: T / k - a, why: `طرحتي $${a}$ مرة تانية! العملية الأصلية كانت طرح، وعكسها **الجمع**.` },
    ]),
    why: `نبدأ من الآخر: $${T}$.\n\nنرجّع الضرب بالقسمة: $${T} ÷ ${k} = ${T / k}$.\n\nنرجّع الطرح بالجمع: $${T / k} + ${a} = ${x}$.\n\nتحقق: $(${x} − ${a}) × ${k} = ${T}$ ✔️`,
  }
}

