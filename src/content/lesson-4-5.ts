const LET = ['س', 'ص', 'ن', 'ع', 'ك', 'م']
const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// هل تشكّل تناسباً؟
const propStoryQ = (): Question => {
  let p: number, q: number
  do { p = rand(1, 9); q = rand(1, 9) } while (p === q || gcd(p, q) !== 1)
  const k1 = rand(2, 6)
  let k2: number
  do { k2 = rand(2, 8) } while (k2 === k1)
  const same = rand(0, 1) === 1
  const x1 = p * k1, y1 = q * k1, x2 = p * k2, y2 = same ? q * k2 : q * k2 + rand(1, 3)
  const c1 = x1 * y2, c2 = y1 * x2
  return {
    kind: 'choice',
    prompt: `قطعت دراجة $${x1}$ كلم في $${y1}$ دقيقة، وقطعت دراجة أخرى $${x2}$ كلم في $${y2}$ دقيقة. هل النسبتان تشكّلان تناسباً؟`,
    options: [
      { text: 'نعم، تشكّلان تناسباً', correct: same,
        why: same
          ? `برافو! 🎉 الضرب التبادلي: $${x1} × ${y2} = ${c1}$ و$${y1} × ${x2} = ${c2}$ متساويان ✔️`
          : `قريبة! 🔍 الضرب التبادلي: $${c1}$ و$${c2}$ مختلفان، يعني **مش** تناسب.` },
      { text: 'لا، لا تشكّلان تناسباً', correct: !same,
        why: !same
          ? `ممتاز! ⭐ الضرب التبادلي: $${c1}$ و$${c2}$ مختلفان ✔️`
          : `قريبة! 🔍 الضرب التبادلي: $${c1}$ و$${c2}$ متساويان، يعني تناسب.` },
    ],
  }
}

// حل التناسب
const solveQ = (): Question => {
  let a: number, b: number
  do { a = rand(2, 9); b = rand(2, 9) } while (a === b)
  const k = rand(2, 9), v = pick(LET)
  const qd = [a, b, a * k, b * k]
  const u = rand(0, 3), o = 3 - u
  const others = [0, 1, 2, 3].filter((i) => i !== u && i !== o)
  const P = qd[others[0]] * qd[others[1]]
  const ans = qd[u]
  const m = u ^ 1, s = (u + 2) % 4
  const add = qd[s] + qd[m] - qd[s ^ 1]
  const s4 = qd.map((x, i) => (i === u ? v : String(x)))
  const wrong = [{ value: P, why: `نسيتي تقسمي على $${qd[o]}$! 😅 بعد الضرب التبادلي لسا لازم نقسم.` }]
  if (add > 0) wrong.push({ value: add, why: 'جمعتي الفرق بدل الضرب! 🔄 التناسب بيتحل بالضرب التبادلي 💡' })
  return {
    kind: 'numeric',
    prompt: `حلّي التناسب $${fr(s4[0], s4[1])} = ${fr(s4[2], s4[3])}$ ثم اكتبي قيمة $${v}$.`,
    answer: ans,
    wrong: wr(ans, wrong),
    why: `الضرب التبادلي: $${v} × ${qd[o]} = ${qd[others[0]]} × ${qd[others[1]]} = ${P}$\n\nنقسم على $${qd[o]}$: $${v} = ${P} ÷ ${qd[o]} = ${ans}$\n\nتحقق: الناتجان التبادليان متساويان ✔️`,
  }
}

// مسألة حياتية
const wordQ = (): Question => {
  const a = rand(1, 5), b = rand(a + 1, 9), k = rand(2, 9)
  const T = pick([
    { s: `نسبة الملح إلى الماء في سائل $${a}$ إلى $${b}$. إذا احتوى السائل على $${b * k}$ جم من الماء، فكم جراماً من الملح فيه؟`, ans: a * k },
    { s: `من كل $${b}$ مصابين يتلقى $${a}$ العلاج. إذا كان هناك $${b * k}$ مصاباً، فكم شخصاً يتلقى العلاج؟`, ans: a * k },
    { s: `تركض سلمى $${a * 10}$ متراً في $${b}$ ثوانٍ. كم متراً تركض في $${b * k}$ ثانية بنفس المعدل؟`, ans: a * 10 * k },
  ])
  return {
    kind: 'numeric',
    prompt: T.s,
    answer: T.ans,
    wrong: wr(T.ans, [
      { value: b * k, why: 'هاد الرقم المعطى نفسه! 🔍 دورنا على الكمية التانية.' },
      { value: T.ans / k * 1 + b * k - b, why: 'جمعتي الفرق بدل ما تضربي! 😅 الكميات **متناسبة**.' },
    ]),
    why: `نكتب التناسب ونحله بالضرب التبادلي، أو بمعدل الوحدة: كل جزء ×$${k}$.\n\nالناتج: $${T.ans}$ ✔️`,
  }
}

