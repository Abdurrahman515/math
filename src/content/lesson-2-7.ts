import { sg } from '../lib/int'

const term = (n: number) => (n < 0 ? `(${sg(n)})` : String(n))
const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

const nextQ = (): Question => {
  const d = rand(2, 9) * (rand(0, 1) ? 1 : -1)
  const a0 = rand(-20, 20)
  const seq = [0, 1, 2, 3, 4].map((i) => a0 + i * d)
  const ans = a0 + 5 * d
  return {
    kind: 'numeric',
    prompt: `اكتبي العدد التالي في النمط:\n$${seq.map(sg).join('، ')}، ؟$`,
    answer: ans,
    wrong: wr(ans, [
      { value: seq[4] - d, why: `النمط ${d > 0 ? 'بيزيد' : 'بينقص'} كل مرة، فمنكمّل بنفس الاتجاه.` },
      { value: ans + (d > 0 ? 1 : -1), why: `الفرق ثابت = $${sg(d)}$ بين كل عددين متجاورين.` },
    ]),
    why: `الفرق بين كل عددين = $${sg(d)}$ ← $${sg(seq[4])} + ${term(d)} = ${sg(ans)}$`,
  }
}

const rateQ = (): Question => {
  const a = rand(2, 5), b = a + rand(1, 4), m = rand(4, 9)
  const c = b * m
  return {
    kind: 'numeric',
    prompt: `يسجّل لاعب $${a}$ أهداف من كل $${b}$ ركلات. كم هدفاً يمكنه أن يسجّل من $${c}$ ركلة؟`,
    answer: a * m,
    wrong: wr(a * m, [{ value: m, why: `هاد عدد **المجموعات** ($${c} ÷ ${b}$)، وكل مجموعة فيها $${a}$ أهداف.` }]),
    why: `كل $${b}$ ركلات ← $${a}$ أهداف. وعندنا $${m}$ مجموعات: $${a} × ${m} = ${a * m}$`,
  }
}

const saveQ = (): Question => {
  const f = rand(2, 9) * 10, d = rand(2, 9) * 5, n = rand(5, 10)
  const T = f + d * (n - 1)
  return {
    kind: 'numeric',
    prompt: `يدّخر محمد نقوداً: بعد شهر واحد عنده $${f}$ ريالاً، وبعد شهرين $${f + d}$، وبعد $3$ أشهر $${f + 2 * d}$، ويستمر النمط. بعد كم شهراً يصل ادخاره إلى $${T}$ ريالاً؟`,
    answer: n,
    wrong: wr(n, [
      { value: n - 1, why: `الشهر الأول **عنده** $${f}$ أصلاً، وبعدين بنزيد $${d}$ لكل شهر إضافي. عدّي الشهر الأول كمان.` },
      { value: n + 1, why: 'عدّيتي شهر زيادة. وقفي لما توصلي للمبلغ بالضبط.' },
    ]),
    why: `الزيادة كل شهر $${d}$. من $${f}$ إلى $${T}$ الفرق $${T - f} = ${n - 1} × ${d}$ ← $${n - 1}$ قفزات بعد الشهر الأول ← الشهر رقم $${n}$`,
  }
}

