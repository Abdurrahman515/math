const functionPractice = (): Question => {
  const coefficient = rand(2, 9)
  const input = rand(2, 9)
  const answer = coefficient * input
  return {
    kind: 'numeric',
    prompt: `قاعدة الدالة هي $y = ${coefficient}x$. إذا كان الإدخال $x = ${input}$، فما المخرج $y$؟`,
    answer,
    wrong: [
      { value: coefficient * (input - 1), why: `استخدمتِ الإدخال السابق ${input - 1} بدلاً من ${input}. عوّضي عن x بالقيمة المعطاة نفسها: ${coefficient} × ${input}.` },
      { value: coefficient * (input + 1), why: `استخدمتِ الإدخال التالي ${input + 1} بدلاً من ${input}. القاعدة تطلب ضرب ${coefficient} في ${input}.` },
      { value: answer + 1, why: 'أضفتِ واحداً إلى الناتج رغم أن قاعدة الدالة هنا ضرب فقط، ولا تتضمن إضافة.' },
    ],
    why: `نعوّض عن x بـ ${input}: $y = ${coefficient} × ${input} = ${answer}$. إذن المخرج هو ${answer}.`,
    fallback: 'استبدلي x بقيمة الإدخال ثم نفّذي قاعدة الدالة؛ هنا نضرب في العدد الثابت.',
  }
}

