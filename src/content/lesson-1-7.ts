import { rand } from '../lib/rng'

const distributiveQ = (): Question => {
  const a = rand(2, 7)
  const b = rand(3, 20)
  const c = rand(2, 9)
  const answer = a * (b + c)
  const wrong = [
    { value: a * b + c, why: `وزّعتِ الضرب على ${b} فقط وتركتي ${c} كما هو. لازم نضرب ${a} في كل حد داخل القوسين: ${a}×${b} و${a}×${c}.` },
    { value: a * b, why: `حسبتِ ${a}×${b} ونسيتِ الحد الثاني داخل القوسين. الخاصية التوزيعية تعني أن نضرب ${a} في ${b} وفي ${c} ثم نجمع الناتجين.` },
    { value: answer + a, why: `الناتج أكبر من المطلوب بمقدار ${a}. بعد توزيع الضرب، نجمع ${a * b} و${a * c}، ولا نضيف ${a} مرة أخرى.` },
  ]
  return {
    kind: 'numeric',
    prompt: `استعملي خاصية التوزيع واحسبي: $${a} × (${b} + ${c})$`,
    answer,
    wrong,
    why: `نوزّع ${a} على العددين داخل القوسين: $${a}×${b} + ${a}×${c} = ${a * b} + ${a * c} = ${answer}$.`,
    fallback: 'اضربي العدد خارج القوس في كل عدد داخله، ثم اجمعي الناتجين.',
  }
}

