const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

const perimeterQ = (): Question => {
  const l = rand(3, 20), w = rand(2, 15)
  const P = 2 * (l + w)
  return {
    kind: 'numeric',
    prompt: `مستطيل طوله $${l}$ سم وعرضه $${w}$ سم. أوجدي محيطه بالسنتيمتر.`,
    answer: P,
    wrong: wr(P, [
      { value: l + w, why: 'هاد **نصف** المحيط! المحيط هو المسافة حول الشكل كله: فيه طولين وعرضين.' },
      { value: l * w, why: 'هاد **المساحة**! المحيط بنجمعه ولا بنضربه: مح = ٢ × (ل + ض).' },
      { value: 2 * l + w, why: 'ضاعفتي الطول بس! بالمستطيل **ضلعين** طول **وضلعين** عرض.' },
    ]),
    why: `مح = ٢ × (ل + ض) = $2 × (${l} + ${w}) = 2 × ${l + w} = ${P}$ سم.`,
  }
}

const areaQ = (): Question => {
  const l = rand(3, 20), w = rand(2, 15)
  const A = l * w
  return {
    kind: 'numeric',
    prompt: `مستطيل طوله $${l}$ م وعرضه $${w}$ م. أوجدي مساحته بالمتر المربع.`,
    answer: A,
    wrong: wr(A, [
      { value: 2 * (l + w), why: 'هاد **المحيط**! المساحة بنحسبها بـ**الضرب**: م = ل × ض.' },
      { value: l + w, why: 'هاد جمع! المساحة عدد المربعات داخل الشكل: بنضرب الطول بالعرض.' },
    ]),
    why: `م = ل × ض = $${l} × ${w} = ${A}$ متراً مربعاً.`,
  }
}

const perimUnknownQ = (): Question => {
  const l = rand(5, 25), w = rand(3, 20)
  const P = 2 * (l + w)
  return {
    kind: 'numeric',
    prompt: `حديقة مستطيلة عرضها $${w}$ م ومحيطها $${P}$ م. ما طولها بالمتر؟`,
    answer: l,
    wrong: wr(l, [
      { value: P / 2, why: `هاد **ل + ض**! لسا لازم نطرح العرض $${w}$.` },
      { value: P - 2 * w, why: 'هاد **٢ل**! لسا لازم نقسم على ٢ بعد ما نطرح.' },
      { value: P - w, why: 'المحيط فيه **عرضين** مو عرض واحد: بنطرح $2 × ' + w + '$.' },
    ]),
    why: `المعادلة: $2ل + 2 × ${w} = ${P}$ ، يعني $2ل + ${2 * w} = ${P}$.\n\nنطرح $${2 * w}$: $2ل = ${P - 2 * w}$ ، ونقسم على $2$: $ل = ${l}$ م.\n\nتحقق: $2 × (${l} + ${w}) = ${P}$ ✔️`,
  }
}

const areaUnknownQ = (): Question => {
  const l = rand(4, 15), w = rand(3, 14)
  const A = l * w
  return {
    kind: 'numeric',
    prompt: `مستطيل مساحته $${A}$ م² وطوله $${l}$ م. ما عرضه بالمتر؟`,
    answer: w,
    wrong: wr(w, [
      { value: A - l, why: 'هاد طرح! المساحة ناتج **ضرب** الطول بالعرض، فبنرجّع **القسمة**.' },
      { value: A * l, why: 'ضربتي! المعادلة فيها ضرب أصلاً، وعكسه القسمة.' },
    ]),
    why: `المعادلة: $${l} × ض = ${A}$\n\nنقسم على $${l}$: $ض = ${A} ÷ ${l} = ${w}$ م.\n\nتحقق: $${l} × ${w} = ${A}$ ✔️`,
  }
}

const whichQuantityQ = (): Question => {
  const P = [
    'يريد مالك حديقة مستطيلة أن يحيطها بسياج.',
    'تريد ريم تثبيت شريط زينة على امتداد جدران غرفتها.',
    'يريد نجار وضع إطار خشبي حول لوحة مستطيلة.',
  ]
  const A = [
    'يريد عبد المجيد شراء سجادة تغطي أرض مجلسه.',
    'تريد سعاد طلاء جدار مستطيل.',
    'يريد عامل تغطية سطح طاولة بالرخام.',
  ]
  const isP = rand(0, 1) === 1
  return {
    kind: 'choice',
    prompt: `${pick(isP ? P : A)} ماذا يحتاج أن يحسب؟`,
    options: [
      { text: 'المحيط', correct: isP,
        why: isP ? 'صح! الشي بيمشي **حول** الشكل: المسافة حوله هي المحيط ✔️'
          : 'المحيط هو المسافة **حول** الشكل. هون المطلوب **تغطية سطح**، يعني المساحة.' },
      { text: 'المساحة', correct: !isP,
        why: !isP ? 'صح! المطلوب **تغطية سطح**، يعني عدد المربعات داخل الشكل: المساحة ✔️'
          : 'المساحة هي المنطقة **داخل** الشكل. هون الشي بيمشي حول الشكل: المحيط.' },
      { text: 'الحجم', why: 'الحجم للأجسام الصلبة (ثلاثية الأبعاد)، وهون في شكل مسطّح.' },
    ],
  }
}

const doubleQ = (): Question => {
  const l = rand(3, 8), w = rand(2, 6)
  const P = 2 * (l + w), A = l * w
  const P2 = 2 * (l + 2 * w), A2 = 2 * l * w
  return {
    kind: 'choice',
    prompt: `مستطيل طوله $${l}$ وعرضه $${w}$. إذا ضاعفنا العرض وبقي الطول كما هو، فما الذي يصحّ؟`,
    options: [
      { text: 'المساحة تتضاعف، لكن المحيط لا يتضاعف', correct: true,
        why: `صح! المساحة: $${A}$ ← $${A2}$ (الضعف). والمحيط: $${P}$ ← $${P2}$، وهو مو ضعف $${P}$ لأنو الطول ما تغيّر ✔️` },
      { text: 'المحيط يتضاعف والمساحة تتضاعف أيضاً',
        why: `المحيط صار $${P2}$ وضعف القديم كان $${2 * P}$، فما تضاعف. الطول ثابت وبس العرضين تضاعفوا.` },
      { text: 'المساحة تبقى كما هي والمحيط يتضاعف',
        why: `المساحة صارت $${A2}$ بدل $${A}$، يعني تضاعفت.` },
      { text: 'المساحة والمحيط لا يتغيران',
        why: `المساحة صارت $${A2}$ والمحيط صار $${P2}$، يعني الاثنين تغيّروا.` },
    ],
  }
}

const squareQ = (): Question => {
  const s = rand(2, 12)
  if (rand(0, 1)) {
    return {
      kind: 'numeric',
      prompt: `مربع طول ضلعه $${s}$ سم. أوجدي مساحته بالسنتيمتر المربع.`,
      answer: s * s,
      wrong: wr(s * s, [
        { value: 2 * s, why: 'هاد $s + s$! مساحة المربع هي الضلع **ضرب نفسه**: $م = س × س$.' },
        { value: 4 * s, why: 'هاد **المحيط** (٤ أضلاع)! المساحة هي الضلع ضرب نفسه.' },
      ]),
      why: `م = س × س = $${s} × ${s} = ${s * s}$ سم مربع.`,
    }
  }
  return {
    kind: 'numeric',
    prompt: `مربع طول ضلعه $${s}$ سم. أوجدي محيطه بالسنتيمتر.`,
    answer: 4 * s,
    wrong: wr(4 * s, [
      { value: s * s, why: 'هاد **المساحة**! المحيط هو مجموع الأضلاع الأربعة المتساوية.' },
      { value: 2 * s, why: 'لسا في ضلعين! المربع له **٤** أضلاع.' },
    ]),
    why: `مح = ٤ × س = $4 × ${s} = ${4 * s}$ سم.`,
  }
}

