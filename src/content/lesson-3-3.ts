import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { sg } from '../lib/int'

const LET = ['س', 'ص', 'ن', 'ع', 'ك', 'م']
const term = (n: number) => (n < 0 ? `(${sg(n)})` : String(n))
const coef = (a: number, v: string) => (a < 0 ? `−${-a}${v}` : `${a}${v}`)
const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// حلّ معادلة ضرب: a س = b (مع إشارات)
const mulEqQ = (): Question => {
  const v = pick(LET)
  const a = pick([2, 3, 4, 5, 6, 7, 8, 9]) * (rand(0, 1) ? 1 : -1)
  const ans = pick([2, 3, 4, 5, 6, 7, 8, 9, 10, 12]) * (rand(0, 1) ? 1 : -1)
  const b = a * ans
  return {
    kind: 'numeric',
    prompt: `حلّي المعادلة $${coef(a, v)} = ${sg(b)}$ ثم اكتبي قيمة $${v}$.`,
    answer: ans,
    wrong: wr(ans, [
      { value: b * a, why: `ضربتي $${sg(b)}$ في $${sg(a)}$! المعادلة فيها ضرب، وعكسه **القسمة**: لازم نقسم الطرفين على $${sg(a)}$.` },
      { value: b - a, why: 'هاد طرح! الضرب ما بيتفك بالطرح، عكس الضرب هو **القسمة**.' },
      { value: -ans, why: `انتبهي للإشارة! ناتج قسمة عددين **إشارتيهم متشابهة** موجب، و**مختلفة** سالب. هون $${sg(b)} ÷ ${term(a)} = ${sg(ans)}$.` },
    ]),
    why: `نقسم الطرفين على $${sg(a)}$: $${sg(b)} ÷ ${term(a)} = ${sg(ans)}$ ، يعني $${v} = ${sg(ans)}$.\n\nتحقق: $${sg(a)} × ${term(ans)} = ${sg(b)}$ ✔️`,
  }
}

// اكتشفي الخطأ: قسمة على عدد موجب بدل المعامل السالب
const findErrorQ = (): Question => {
  const a = rand(2, 9), m = rand(2, 12)
  const b = a * m
  return {
    kind: 'choice',
    prompt: `حلّت ليلى المعادلة $−${a}س = ${b}$ هيك: قسمت الطرفين على $${a}$ فكتبت $س = ${m}$. هل حلّها صحيح؟`,
    options: [
      { text: `غير صحيح؛ كان يجب القسمة على $−${a}$ والحل $س = −${m}$`, correct: true,
        why: `صح! المعامل الحقيقي هو $−${a}$ فنقسم عليه مباشرة: $${b} ÷ (−${a}) = −${m}$ ✔️` },
      { text: `صحيح؛ لأن القسمة على $${a}$ مسموحة`,
        why: `القسمة على $${a}$ مسموحة فعلاً، بس بعدها بيصير $−س = ${m}$، يعني لسا في إشارة سالب قدام س. لازم نقسم على المعامل **كامل بإشارته**.` },
      { text: `غير صحيح؛ الحل هو $س = ${-b * m}$`,
        why: `ضربتي بدل ما تقسمي! بمعادلة الضرب بنقسم: $${b} ÷ (−${a}) = −${m}$.` },
      { text: 'صحيح؛ لأن ناتج القسمة موجب دائماً',
        why: 'إشارة الناتج ما بتكون موجبة دايماً؛ بتعتمد على إشارتي العددين: إذا اختلفوا الناتج **سالب**.' },
    ],
  }
}

// معادلات الصيغة ف = ع ن بقصص مختلفة
const rateQ = (): Question => {
  const r = rand(4, 15), n = rand(3, 12), d = r * n
  const S = [
    { s: `تسير سيارة بسرعة ثابتة مقدارها $${r}$ كلم في الساعة. كم ساعة تحتاج لتقطع $${d}$ كلم؟`,
      ans: n, other: r, eq: `${r}ن = ${d}` },
    { s: `ثمن القلم الواحد $${r}$ ريالاً. كم قلماً تشتري بمبلغ $${d}$ ريالاً؟`,
      ans: n, other: r, eq: `${r}س = ${d}` },
    { s: `يدّخر فهد $${r}$ ريالاً كل أسبوع. كم أسبوعاً يلزمه ليجمع $${d}$ ريالاً؟`,
      ans: n, other: r, eq: `${r}ن = ${d}` },
    { s: `يطير عصفور مسافة $${d}$ م في $${n}$ ثانية بسرعة ثابتة. كم متراً يطير في الثانية الواحدة؟`,
      ans: r, other: n, eq: `${n}ع = ${d}` },
  ]
  const t = pick(S)
  return {
    kind: 'numeric',
    prompt: t.s,
    answer: t.ans,
    wrong: wr(t.ans, [
      { value: d * t.other, why: `ضربتي $${d}$ في $${t.other}$! المعادلة فيها ضرب، فنرجّع **القسمة**.` },
      { value: d - t.other, why: 'هاد طرح! عكس الضرب هو **القسمة** مو الطرح.' },
    ]),
    why: `المعادلة: $${t.eq}$\n\nنقسم الطرفين على $${t.other}$: $${d} ÷ ${t.other} = ${t.ans}$.\n\nتأكدي من المعقولية: هل الجواب بيناسب القصة؟`,
  }
}

// أي معادلة تمثل المسألة
const writeEqQ = (): Question => {
  const k = rand(3, 12), m = rand(2, 9), T = k * m
  const S = [
    `اشترت سمية س كيلوجراماً من الدقيق، وسعر الكيلوجرام $${k}$ ريالاً، ودفعت $${T}$ ريالاً. أي معادلة تمثّل المسألة؟`,
    `اشترى خالد س كيلوجراماً من التمر، وسعر الكيلوجرام $${k}$ ريالاً، ودفع $${T}$ ريالاً. أي معادلة تمثّل المسألة؟`,
    `اشترت نورة س علبة عصير، وثمن العلبة $${k}$ ريالاً، ودفعت $${T}$ ريالاً. أي معادلة تمثّل المسألة؟`,
  ]
  return {
    kind: 'choice',
    prompt: pick(S),
    options: [
      { text: `$${k}س = ${T}$`, correct: true,
        why: 'صح! كل واحدة بسعر ثابت، فالدفع الكلي هو السعر **ضرب** العدد.' },
      { text: `$س + ${k} = ${T}$`, why: 'هاد جمع! السعر بيتكرر مع كل قطعة، فالعملية **ضرب** مو جمع.' },
      { text: `$س ÷ ${k} = ${T}$`, why: 'هاد قسمة! الكمية الكلية مضروبة بالسعر، مو مقسومة عليه.' },
      { text: `$س − ${k} = ${T}$`, why: 'هاد طرح! ما في شي بينشال هون، السعر بيتكرر: **ضرب**.' },
    ],
  }
}

