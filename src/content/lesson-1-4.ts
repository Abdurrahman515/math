/** تدريب متجدد على استراتيجية التخمين والتحقق باستخدام أسعار الغسيل في المثال. */
const carWashQ = (): Question => {
  const totalCars = rand(6, 12)
  const largeCars = rand(2, totalCars - 2)
  const smallCars = totalCars - largeCars
  const target = smallCars * 10 + largeCars * 20

  return {
    kind: 'numeric',
    prompt: `في مغسلة سيارات: غسيل السيارة الصغيرة 10 ريالات، والكبيرة 20 ريالاً. غُسلت ${totalCars} سيارات بمبلغ ${target} ريالاً. كم سيارة كبيرة غُسلت؟`,
    answer: largeCars,
    wrong: [
      {
        value: largeCars - 1,
        why: `لو كان عدد السيارات الكبيرة ${largeCars - 1} فقط، فسيقلّ المبلغ 10 ريالات؛ لأننا استبدلنا غسيلاً كبيراً (20) بغسيل صغير (10).`,
      },
      {
        value: largeCars + 1,
        why: `لو كان عدد السيارات الكبيرة ${largeCars + 1}، فسيزيد المبلغ 10 ريالات عن المطلوب. نحتاج ${largeCars} سيارات كبيرة حتى يطابق المجموع ${target} ريالاً.`,
      },
    ],
    why: `نجرب ${largeCars} سيارات كبيرة، فيبقى ${smallCars} سيارات صغيرة. المبلغ: $${largeCars} × 20 + ${smallCars} × 10 = ${largeCars * 20} + ${smallCars * 10} = ${target}$ ريالاً. إذن التخمين صحيح.`,
    fallback: 'اكتبي تخميناً ثم اختبريه: هل مجموع أعداد السيارات يساوي العدد المعطى؟ وهل مجموع الأسعار يساوي المبلغ؟',
  }
}

