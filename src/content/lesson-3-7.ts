import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { sg } from '../lib/int'

const term = (n: number) => (n < 0 ? `(${sg(n)})` : String(n))
const rule = (m: number, b: number) =>
  `${m === 1 ? '' : m === -1 ? '−' : sg(m)}س${b > 0 ? ` + ${b}` : b < 0 ? ` − ${-b}` : ''}`
const nzv = (m: number) => rand(1, m) * (rand(0, 1) ? 1 : -1)
const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// قيمة ص عند س معيّنة
const tableQ = (): Question => {
  const m = pick([2, 3, 4, 5, -2, -3])
  const b = nzv(6)
  const s = nzv(4)
  const ans = m * s + b
  return {
    kind: 'numeric',
    prompt: `إذا كانت $ص = ${rule(m, b)}$ ، فما قيمة $ص$ عندما $س = ${sg(s)}$ ؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: m * s, why: `نسيتي الحد الثابت $${sg(b)}$! بعد ما نضرب لازم ${b > 0 ? 'نجمع' : 'نطرح'} الثابت.` },
      { value: m + s + b, why: `جمعتي كل الأعداد! $${sg(m)}س$ معناها $${sg(m)}$ **ضرب** $س$.` },
      { value: m * (s + b), why: 'ضربتي بعد الجمع! الضرب بيصير **أول** (ترتيب العمليات)، وبعدين الجمع.' },
    ]),
    why: `نعوّض: $ص = ${term(m)} × ${term(s)} ${b > 0 ? '+' : '−'} ${Math.abs(b)} = ${sg(m * s)} ${b > 0 ? '+' : '−'} ${Math.abs(b)} = ${sg(ans)}$.\n\nإذن الزوج المرتب: $(${sg(s)} ، ${sg(ans)})$.`,
  }
}

// أي زوج مرتب حل للمعادلة
const isSolutionQ = (): Question => {
  let m = 0, b = 0, x = 0, y = 0
  do {
    m = pick([2, 3, 4])
    b = nzv(5)
    x = nzv(4)
    y = m * x + b
  } while (y === x)
  const pair = (px: number, py: number) => `(${sg(px)} ، ${sg(py)})`
  const cands = [
    { px: y, py: x },
    { px: x, py: m * x - b },
    { px: x, py: m + x + b },
    { px: x, py: y + 1 },
    { px: x, py: y - 1 },
  ]
  const seen = new Set([pair(x, y)])
  const wrongs = cands
    .filter((c) => (seen.has(pair(c.px, c.py)) ? false : (seen.add(pair(c.px, c.py)), true)))
    .slice(0, 3)
  return {
    kind: 'choice',
    prompt: `أي الأزواج المرتبة الآتية هو **حل** للمعادلة $ص = ${rule(m, b)}$ ؟`,
    options: [
      { text: `$${pair(x, y)}$`, correct: true,
        why: `صح! عوّضنا $س = ${sg(x)}$: $${term(m)} × ${term(x)} ${b > 0 ? '+' : '−'} ${Math.abs(b)} = ${sg(y)}$ ✔️` },
      ...wrongs.map((c) => ({
        text: `$${pair(c.px, c.py)}$`,
        why: c.px === y && c.py === x
          ? 'عكستي ترتيب الإحداثيين! الأول **س** والتاني **ص**.'
          : `عوّضنا $س = ${sg(c.px)}$ فطلع $ص = ${sg(m * c.px + b)}$ ، مو $${sg(c.py)}$ ، يعني النقطة **مو** على المستقيم.`,
      })),
    ],
  }
}

// دالة ف = م ن (سباحة)
const swimQ = (): Question => {
  const m = pick([50, 60, 80, 100, 120]), n = rand(2, 5)
  return {
    kind: 'choice',
    prompt: `يقطع سبّاح $${m}$ متراً في كل دقيقة، فالمعادلة $ف = ${m}ن$ تمثّل المسافة $ف$ بعد $ن$ دقيقة. أي الأزواج المرتبة $(ن ، ف)$ يقع على التمثيل البياني للدالة؟`,
    options: [
      { text: `$(${n} ، ${m * n})$`, correct: true,
        why: `صح! بعد $${n}$ دقيقة المسافة $${m} × ${n} = ${m * n}$ متر ✔️` },
      { text: `$(${m * n} ، ${n})$`, why: 'عكستي الترتيب! الأول **ن** (الزمن) والتاني **ف** (المسافة).' },
      { text: `$(${n} ، ${m + n})$`, why: `جمعتي بدل ما تضربي! بعد $${n}$ دقيقة المسافة $${m} × ${n}$ مو $${m} + ${n}$.` },
      { text: `$(${m} ، ${n})$`, why: `هاي بتقول إنو بعد $${m}$ دقيقة قطع $${n}$ متر بس، وهاد غير منطقي مع سرعة $${m}$ متر بالدقيقة.` },
    ],
  }
}

// اكتبي معادلة الدالة
const writeRuleQ = (): Question => {
  if (rand(0, 1)) {
    const k = rand(3, 9)
    return {
      kind: 'choice',
      prompt: `سعر القلم الواحد $${k}$ ريالات. أي معادلة تمثّل التكلفة $ص$ لشراء $س$ قلماً؟`,
      options: [
        { text: `$ص = ${k}س$`, correct: true, why: 'صح! كل قلم بسعر ثابت، فالتكلفة هي السعر **ضرب** العدد ✔️' },
        { text: `$ص = س + ${k}$`, why: 'هيك السعر بينزاد مرة وحدة على عدد الأقلام، والمفروض يتكرر مع كل قلم.' },
        { text: `$ص = س ÷ ${k}$`, why: 'القسمة بتصغّر الناتج، والتكلفة بتكبر بزيادة الأقلام: **ضرب**.' },
        { text: `$ص = ${k} − س$`, why: 'هيك التكلفة بتنقص كل ما زادت الأقلام! والمنطق العكس.' },
      ],
    }
  }
  const f = rand(20, 60), u = rand(5, 15)
  return {
    kind: 'choice',
    prompt: `رسم الاشتراك في نادٍ $${f}$ ريالاً **مرة واحدة**، ثم $${u}$ ريالات كل شهر. أي معادلة تمثّل المبلغ الكلي $ص$ بعد $س$ شهراً؟`,
    options: [
      { text: `$ص = ${u}س + ${f}$`, correct: true, why: 'صح! الشهري بيتكرر (ضرب)، ورسم الاشتراك بينزاد **مرة وحدة** ✔️' },
      { text: `$ص = (${u} + ${f})س$`, why: 'هيك بنكون عم ندفع رسم الاشتراك **كل شهر**، وهو مرة وحدة بس.' },
      { text: `$ص = ${u} + ${f}س$`, why: 'هيك رسم الاشتراك هو اللي بيتكرر، والمفروض الشهري هو اللي بيتكرر.' },
      { text: `$ص = ${u}س − ${f}$`, why: 'رسم الاشتراك **بينزاد** على المبلغ الكلي مو بينطرح.' },
    ],
  }
}

