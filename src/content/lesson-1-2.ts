import type { Lesson, Question } from '../types'
import { rand } from '../lib/rng'

const powQ = (): Question => {
  const b = rand(2, 5), e = rand(2, 4), ans = b ** e
  const cand = [
    { value: b * e, why: `ضربتي الأساس بالأس ($${b} × ${e}$). بس الأس بيقول **كم مرة** منكرر الأساس.` },
    { value: e ** b, why: `قلبتي الأساس مع الأس! الأساس هو $${b}$ (اللي منكرره) والأس هو $${e}$ (عدد التكرار).` },
    { value: b ** (e - 1), why: `كررتي الأساس مرّة أقل من اللازم. لازم ${e} عوامل مش ${e - 1}.` },
  ]
  const seen = new Set([ans])
  const wrong = cand.filter((w) => { if (seen.has(w.value)) return false; seen.add(w.value); return true })
  return {
    kind: 'numeric',
    prompt: `احسبي قيمة $${b}^${e}$`,
    answer: ans,
    wrong,
    why: `$${Array(e).fill(b).join(' × ')} = ${ans}$`,
  }
}

