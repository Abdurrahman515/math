import type { Lesson, Question } from '../types'
import { rand } from '../lib/rng'


const equationQ = (): Question => {
  const kind = rand(0, 3)
  let op: '+' | '−' | '×' | '÷'
  let constant: number
  let answer: number
  let target: number

  if (kind === 0) {
    op = '+'
    answer = rand(3, 25)
    constant = rand(2, 15)
    target = answer + constant
  } else if (kind === 1) {
    op = '−'
    answer = rand(12, 30)
    constant = rand(2, 9)
    target = answer - constant
  } else if (kind === 2) {
    op = '×'
    answer = rand(2, 12)
    constant = rand(2, 9)
    target = answer * constant
  } else {
    op = '÷'
    constant = rand(2, 9)
    target = rand(2, 12)
    answer = target * constant
  }

  const left = (x: number) =>
    op === '+' ? x + constant
      : op === '−' ? x - constant
        : op === '×' ? x * constant
          : x / constant

  const wrong = [answer - 1, answer + 1].map((value) => ({
    value,
    why: `لو عوّضنا عن $س$ بـ ${value}، يصبح الطرف الأيسر ${Number(left(value).toFixed(3))} بدلاً من ${target}. الحل هو القيمة التي تجعل الطرفين متساويين.`,
  }))

  const inverse =
    op === '+' ? `نطرح ${constant} من الطرفين`
      : op === '−' ? `نضيف ${constant} إلى الطرفين`
        : op === '×' ? `نقسم الطرفين على ${constant}`
          : `نضرب الطرفين في ${constant}`

  const steps =
    op === '+' ? `${target} − ${constant} = ${answer}`
      : op === '−' ? `${target} + ${constant} = ${answer}`
        : op === '×' ? `${target} ÷ ${constant} = ${answer}`
          : `${target} × ${constant} = ${answer}`

  return {
    kind: 'numeric',
    prompt: `حلّي المعادلة ذهنياً: $س ${op} ${constant} = ${target}$. ما قيمة س؟`,
    answer,
    wrong,
    why: `${inverse}، فنحصل على $س = ${answer}$ لأن ${steps}.`,
    fallback: 'اختاري العملية العكسية التي تعيدنا إلى قيمة س وحدها، ثم تحققي بالتعويض.',
  }
}


