// تحقّقي بالتعويض: أي قيمة هي الحل
const checkQ = (): Question => {
  const v = pick(LET), isAdd = rand(0, 1) === 1, a = rand(2, 12), b = rand(5, 25)
  const ans = isAdd ? b - a : b + a
  const lhs = (x: number) => (isAdd ? x + a : x - a)
  const eq = isAdd ? `${v} + ${a} = ${b}` : `${v} − ${a} = ${b}`
  const vals = Array.from(new Set([ans, b, a, -ans])).slice(0, 4)
  if (!vals.includes(ans)) vals[0] = ans
  return {
    kind: 'choice',
    prompt: `أي قيمة من القيم الآتية هي حل المعادلة $${eq}$ ؟ تأكدي بالتعويض.`,
    options: vals.map((x) => ({
      text: `$${v} = ${sg(x)}$`,
      correct: x === ans,
      why: x === ans
        ? `صح! عوّضنا: $${sg(x)} ${isAdd ? '+' : '−'} ${a} = ${sg(lhs(x))}$ وهذا يساوي $${b}$ ✔️`
        : `عوّضنا: $${sg(x)} ${isAdd ? '+' : '−'} ${a} = ${sg(lhs(x))}$ وهذا مو $${b}$، يعني الطرفين مو متساويين.`,
    })),
  }
}

