const LET = ['س', 'ص', 'ن', 'ع', 'ك', 'م']

const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// حلّ معادلة جمع: س + a = b
const addEqQ = (): Question => {
  const v = pick(LET), a = rand(2, 15), b = rand(-12, 30), ans = b - a
  return {
    kind: 'numeric',
    prompt: `حلّي المعادلة $${v} + ${a} = ${sg(b)}$ ثم اكتبي قيمة $${v}$.`,
    answer: ans,
    wrong: wr(ans, [
      { value: a + b, why: `جمعتي $${a}$ على $${sg(b)}$! عملية الجمع هي اللي بالمعادلة، وعكسها **الطرح**: لازم نطرح $${a}$ من الطرفين.` },
      { value: a - b, why: `قلبتي الترتيب! بنطرح $${a}$ **من** $${sg(b)}$ مو العكس: $${sg(b)} − ${a}$.` },
    ]),
    why: `نطرح $${a}$ من الطرفين: $${sg(b)} − ${a} = ${sg(ans)}$ ، يعني $${v} = ${sg(ans)}$.\n\nتحقق: $${sg(ans)} + ${a} = ${sg(b)}$ ✔️`,
  }
}

// حلّ معادلة طرح: س − a = b
const subEqQ = (): Question => {
  const v = pick(LET), a = rand(2, 15), b = rand(-12, 25), ans = a + b
  return {
    kind: 'numeric',
    prompt: `حلّي المعادلة $${v} − ${a} = ${sg(b)}$ ثم اكتبي قيمة $${v}$.`,
    answer: ans,
    wrong: wr(ans, [
      { value: b - a, why: `طرحتي $${a}$ مرة تانية! المعادلة فيها طرح، وعكسه **الجمع**: لازم نضيف $${a}$ للطرفين.` },
      { value: a - b, why: `قلبتي الترتيب! بنضيف $${a}$ على $${sg(b)}$: $${sg(b)} + ${a}$.` },
    ]),
    why: `نضيف $${a}$ للطرفين: $${sg(b)} + ${a} = ${sg(ans)}$ ، يعني $${v} = ${sg(ans)}$.\n\nتحقق: $${sg(ans)} − ${a} = ${sg(b)}$ ✔️`,
  }
}

type Story = { s: string; ok: string; bad: [string, string][] }

