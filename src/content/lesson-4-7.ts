import type { Lesson, Question } from '../types'
import { pick, rand } from '../lib/rng'
import { dec, r3 } from '../lib/dec'

const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

// من الخريطة إلى الواقع
const mapQ = (): Question => {
  const k = pick([5, 10, 20, 24, 25, 40, 50, 100]), d = rand(4, 32) / 2, ans = d * k
  return {
    kind: 'numeric',
    prompt: `مقياس رسم خريطة $1$ سم = $${k}$ كلم. المسافة بين مدينتين على الخريطة $${dec(d)}$ سم. ما المسافة الفعلية بالكيلومتر؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: r3(d + k), why: 'هاد جمع! 🔄 كل ١ سم بيمثل ' + k + ' كلم، فنضرب.' },
      { value: k, why: 'هاد مسافة ١ سم بس! 🔍 المسافة على الخريطة ' + dec(d) + ' سم.' },
      { value: r3(k / d), why: 'قلبتي القسمة! 😅 نكتب تناسباً ونضرب تبادلياً.' },
    ]),
    why: `التناسب: $1 : ${k} = ${dec(d)} : ف$\n\nالضرب التبادلي: $ف = ${dec(d)} × ${k} = ${dec(ans)}$ كلم ✔️`,
  }
}

// من الواقع إلى المخطط
const planQ = (): Question => {
  const k = pick([2, 3, 4, 5, 6]), d = rand(3, 20), L = d * k
  return {
    kind: 'numeric',
    prompt: `مقياس رسم مخطط شقة $1$ سم = $${k}$ م. الطول الفعلي للصالة $${L}$ م. كم سنتمتراً طولها على المخطط؟`,
    answer: d,
    wrong: wr(d, [
      { value: L * k, why: 'ضربتي! 🔄 الطول على المخطط **أصغر** من الفعلي، فنقسم.' },
      { value: L - k, why: 'هاد طرح! 😅 نكتب تناسباً.' },
      { value: k, why: 'هاد مقياس ١ سم! 🔍 الصالة أطول من ١ سم على المخطط.' },
    ]),
    why: `التناسب: $1 : ${k} = ن : ${L}$\n\n$${k} × ن = ${L}$ ← $ن = ${L} ÷ ${k} = ${d}$ سم ✔️`,
  }
}

// تكبير نموذج
const modelQ = (): Question => {
  const a = pick([2, 3, 4, 5]), m = rand(3, 20), ans = a * m
  return {
    kind: 'numeric',
    prompt: `صمّم رسّام إعلاناً لهاتف طوله $${m}$ سم باستعمال المقياس $${a}$ سم = $1$ سم. كم يبلغ طول الهاتف في الإعلان؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: r3(m / a), why: 'قسمتي! 🔄 هون الإعلان **أكبر** من الهاتف الحقيقي (المقياس بيكبّر).' },
      { value: m + a, why: 'هاد جمع! 😅 نكتب تناسباً.' },
      { value: a, why: 'هاد رقم المقياس بس! 🔍 لازم نضربه بالطول.' },
    ]),
    why: `التناسب: $${a} : 1 = س : ${m}$\n\n$1 × س = ${a} × ${m}$ ← $س = ${ans}$ سم ✔️`,
  }
}

// عامل المقياس
const factorQ = (): Question => {
  const m = rand(2, 9)
  return {
    kind: 'choice',
    prompt: `ما عامل المقياس في نموذج طائرة إذا كان المقياس $1$ سم = $${m}$ أمتار؟`,
    options: [
      { text: `$1 : ${100 * m}$`, correct: true, why: `برافو! 🎉 حوّلنا $${m}$ م إلى $${100 * m}$ سم لتصير الوحدتان متشابهتين فتختفيان ✔️` },
      { text: `$1 : ${m}$`, why: 'نسيتي تحوّلي الأمتار لسنتمترات! 😅 عامل المقياس بيكون **بدون وحدات**.' },
      { text: `$${100 * m} : 1$`, why: 'قلبتي النسبة! 🔄 قياس الرسم بالبسط والحقيقي بالمقام.' },
      { text: `$1 : ${10 * m}$`, why: 'المتر = ١٠٠ سنتمتر مو ١٠! 🔍 عدّي الأصفار.' },
    ],
  }
}

