const wr = (answer: number, list: { value: number; why: string }[]) => {
  const seen = new Set([answer])
  return list.filter((w) => (seen.has(w.value) ? false : (seen.add(w.value), true)))
}

const bounceQ = (): Question => {
  const n = rand(3, 4), m = rand(1, 5), H = m * 2 ** n
  return {
    kind: 'numeric',
    prompt: `سقطت كرة من ارتفاع $${H}$ م، وكانت ترتد كل مرة إلى نصف الارتفاع السابق. ارسمي الارتدادات: ما الارتفاع بعد الارتداد رقم $${n}$؟`,
    answer: m,
    wrong: wr(m, [
      { value: H / 2, why: 'هاد الارتداد الأول بس! 🏀 كمّلي الرسم لحد الارتداد المطلوب.' },
      { value: 2 * m, why: 'وقفتي قبل ارتداد! 🔍 عدّي الارتدادات من رسمك.' },
      { value: m / 2, why: 'زدتي ارتداداً زيادة! 😅 الارتداد رقم ' + n + ' هو الأخير.' },
    ]),
    why: `نرسم كل ارتداد ونقسم الارتفاع السابق على ٢:\n\n${Array.from({ length: n }, (_, i) => `الارتداد ${i + 1}: $${H / 2 ** (i + 1)}$ م`).join('\n\n')}\n\nالجواب: $${m}$ م ✔️`,
  }
}

const leftQ = (): Question => {
  const [p, q] = pick([[2, 3], [3, 5], [2, 5], [3, 4], [4, 5], [1, 3], [3, 8]])
  const u = rand(5, 20), d = p * u, ans = (q - p) * u
  return {
    kind: 'numeric',
    prompt: `قطع عدنان $${d}$ م، وهي تمثّل $${fr(p, q)}$ الطريق إلى منزل شقيقه. ارسمي الطريق: كم متراً بقي عليه؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: q * u, why: 'هاد طول الطريق كله! 🛣️ السؤال عن المتبقي.' },
      { value: u, why: `هاد جزء واحد بس! 🔍 المتبقي $${q - p}$ من الأجزاء.` },
      { value: d, why: 'هاد اللي قطعه عدنان! 😅 نبحث عن اللي بقي.' },
    ]),
    why: `نقسم الطريق إلى $${q}$ أجزاء، كل جزء $${d} ÷ ${p} = ${u}$ م.\n\nالمتبقي $${q - p}$ من الأجزاء: $${q - p} × ${u} = ${ans}$ م ✔️`,
  }
}

const matchesQ = (): Question => {
  const n = rand(4, 9), ans = (n * (n - 1)) / 2
  return {
    kind: 'numeric',
    prompt: `يشارك $${n}$ طلاب في بطولة تنس طاولة، وفي الجولة الأولى يواجه كل لاعب سائر اللاعبين مرة واحدة. ارسمي الخطوط بين اللاعبين: كم مباراة في هذه الجولة؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: n * (n - 1), why: 'عدّيتي كل مباراة **مرتين**! 😅 مباراة (أ مع ب) هي نفسها (ب مع أ).' },
      { value: n - 1, why: 'هاد عدد مباريات لاعب واحد بس! 🔍 لازم نعدّ مباريات الكل.' },
      { value: n * n, why: 'اللاعب ما بيلعب مع نفسه! 🙂 ونكرر العدّ كمان.' },
    ]),
    why: `كل لاعب يواجه $${n - 1}$ لاعبين، فمجموع الخطوط $${n} × ${n - 1} = ${n * (n - 1)}$ لكن كل مباراة انعدّت مرتين.\n\nنقسم على ٢: $${ans}$ مباراة ✔️`,
  }
}

const poolQ = (): Question => {
  const q = rand(3, 8), t = rand(5, 30), ans = q * t
  return {
    kind: 'numeric',
    prompt: `بعد $${t}$ دقيقة، تم ملء $${fr(1, q)}$ بركة سباحة بالماء. ارسمي شريطاً للبركة: كم دقيقة تلزم لملء البركة كاملة إذا كان تدفق الماء ثابتاً؟`,
    answer: ans,
    wrong: wr(ans, [
      { value: t, why: 'هاد الوقت لجزء واحد بس! 🔍 البركة فيها ' + q + ' أجزاء.' },
      { value: (q - 1) * t, why: 'هاد الوقت **المتبقي** بس! 😅 السؤال عن الوقت الكلي.' },
      { value: t + q, why: 'هاد جمع! 🔄 كل جزء بياخد نفس الوقت فنضرب.' },
    ]),
    why: `نقسم البركة إلى $${q}$ أجزاء متساوية، كل جزء بياخد $${t}$ دقيقة.\n\nالكلي: $${q} × ${t} = ${ans}$ دقيقة ✔️`,
  }
}

